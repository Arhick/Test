  // Какие ночные события идут после распределения ресурсов.
  function nightEvents(n, alloc) {
    const P = d().people;
    const out = [];
    if (n === 1) {
      out.push('n_radio1');
      if (P.sergey.here && P.sergey.alive) out.push(alloc.sergey ? 'n_sergey_ok' : 'n_sergey_turn');
      if (P.dyachkov.here) out.push('n_dyachkov');
      if (fl('tookCop')) out.push('n_cop_lisa');
      if (P.kolya.infected && P.kolya.hidden && P.kolya.alive) out.push('n_kolya_hidden');
    } else if (n === 2) {
      if (P.sergey.here && P.sergey.alive && !P.sergey.locked) {
        if (alloc.sergey) {
          S().flag('sergeyStable', true);
          S().decide('sergey', 'Сергей', 'Держится на ингибиторе', 'Каждая доза для него — доза, которой нет у тебя.');
        } else out.push('n_sergey_turn');
      }
      if (P.sergey.locked) out.push('n_sergey_locked');
      if (P.kolya.alive && P.kolya.infected && P.kolya.here && !P.kolya.locked) {
        if (alloc.kolya) {
          S().decide('kolya', 'Коля', 'Держится на ингибиторе', 'Ты делишь дозы с водителем.');
        } else out.push('n_kolya_turn');
      }
      if (fl('mashaStudied')) out.push('n_stupina_radio');
      if (fl('copKilled') && P.lisa.here) out.push('n_cop_pistol');
      out.push('n_radio2');
    }
    return out;
  }

